function titleCaseKey(key) {
  const spaced = String(key).replace(/([A-Z])/g, " $1");
  return spaced.charAt(0).toUpperCase() + spaced.slice(1).trim();
}

/**
 * Builds a short list of scannable "why buy this" bullet points from the
 * product's specs + provenance data whenever the product doesn't already
 * hand-author its own `highlights` array.
 */
function buildHighlights(product) {
  if (product.highlights?.length > 0) return product.highlights;

  const specHighlights = Object.entries(product.specs || {})
    .filter(([key]) => key !== "origin")
    .slice(0, 3)
    .map(([key, value]) => `${titleCaseKey(key)}: ${value}`);

  return [
    ...specHighlights,
    `${product.giTag || "GI Registry"} certified craft, sourced directly from ${product.district}, ${product.state}`,
    `Handmade by ${product.artisanName} of ${product.sellerName} — no factory mass production`,
    "100% of the payment goes directly to the artisan, zero middleman markup",
  ].filter(Boolean);
}

