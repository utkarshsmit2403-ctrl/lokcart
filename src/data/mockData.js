/**
 * Builds a small, seeded set of patron reviews for a product whenever it
 * doesn't already hand-author its own `reviews` array, so every listing has
 * consistent, believable social proof.
 */
function buildReviews(product) {
  if (product.reviews?.length > 0) return product.reviews;

  const seed = product.id || product.name;
  const count = 5;

  return Array.from({ length: count }, (_, i) => {
    const reviewer = seededPick(`${seed}-reviewer-${i}`, REVIEWER_POOL);
    const template = seededPick(`${seed}-template-${i}`, REVIEW_TEMPLATE_POOL);
    return {
      id: `${product.id}-review-${i + 1}`,
      name: reviewer.name,
      city: reviewer.city,
      rating: template.rating,
      title: template.title,
      body: template.body(product),
      date: seededPick(`${seed}-date-${i}`, REVIEW_DATE_POOL),
      verifiedPurchase: true,
      helpfulCount: seededRange(`${seed}-helpful-${i}`, 2, 48),
    };
  });
}

/**
 * Builds a plausible star-rating breakdown (percentage per star) consistent
 * with the product's overall average rating.
 */
function buildRatingBreakdown(product) {
  if (product.ratingBreakdown) return product.ratingBreakdown;

  const rating = product.rating || 4.5;
  if (rating >= 4.8) return { 5: 88, 4: 9, 3: 2, 2: 1, 1: 0 };
  if (rating >= 4.5) return { 5: 78, 4: 15, 3: 4, 2: 2, 1: 1 };
  if (rating >= 4.0) return { 5: 62, 4: 24, 3: 8, 2: 4, 1: 2 };
  return { 5: 45, 4: 30, 3: 15, 2: 7, 1: 3 };
}

