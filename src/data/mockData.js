/**
 * Detects if a search query matches or contains any known Indian craft district.
 * Returns the matching District Name if found, or null if the user did NOT search by a district.
 */
export function detectDistrictFromSearch(query, districtsList = []) {
  if (!query || typeof query !== "string" || !query.trim()) return null;
  const q = query.toLowerCase().trim();

  // Explicit known district map with aliases and clusters
  const aliasMap = {
    bhagalpur: "Bhagalpur",
    madhubani: "Madhubani",
    mithila: "Madhubani",
    varanasi: "Varanasi",
    banaras: "Varanasi",
    kashi: "Varanasi",
    gorakhpur: "Gorakhpur",
    saharanpur: "Saharanpur",
    channapatna: "Channapatna",
    delhi: "Delhi",
    "new delhi": "Delhi",
    aurangabad: "Aurangabad",
    barun: "Aurangabad",
    gaya: "Gaya",
    patna: "Patna",
  };

  for (const [key, val] of Object.entries(aliasMap)) {
    const regex = new RegExp(`(^|\\b|\\s)${key}(\\b|\\s|$)`, "i");
    if (regex.test(q)) {
      return val;
    }
  }

  if (Array.isArray(districtsList)) {
    for (const d of districtsList) {
      if (!d?.name) continue;
      const dName = d.name.toLowerCase();
      const regex = new RegExp(`(^|\\b|\\s)${dName}(\\b|\\s|$)`, "i");
      if (regex.test(q)) {
        return d.name;
      }
    }
  }

  return null;
}